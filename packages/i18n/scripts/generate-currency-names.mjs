/**
 * Regenerates `src/currencyNames.generated.ts` from the CLDR data bundled with Node's Intl.
 *
 * Run with: pnpm --filter @saldo/i18n generate:currency-names
 *
 * Generated rather than asked of the phone: Hermes has no `Intl.DisplayNames`. The name is the one
 * CLDR uses for a single unit ("franco svizzero", "Swiss franc") — sentence case, unlike the
 * title-cased display name — with its first letter raised, since it is shown as a row title.
 * The codes are `Intl.supportedValuesOf('currency')`, as in `@saldo/core`'s generator, so the
 * two stay in step when both are run on the same Node.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(
  dirname(fileURLToPath(import.meta.url)),
  '..',
  'src',
  'currencyNames.generated.ts',
);

/** Keep in step with `SUPPORTED_LOCALES` in `src/format.ts`; `currencyNames.test.ts` checks it. */
const LOCALES = ['it', 'en'];

function nameOf(code, locale) {
  const name = new Intl.NumberFormat(locale, {
    style: 'currency',
    currency: code,
    currencyDisplay: 'name',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  })
    .formatToParts(1)
    .filter((part) => part.type === 'currency')
    .map((part) => part.value)
    .join('')
    .trim();
  if (name === '') throw new Error(`No ${locale} name for ${code}`);
  return name.charAt(0).toLocaleUpperCase(locale) + name.slice(1);
}

const codes = [...Intl.supportedValuesOf('currency')].sort();

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const file = `// Generated by scripts/generate-currency-names.mjs from Node's CLDR data. Do not edit by hand.
// Source: Intl.NumberFormat currencyDisplay 'name', singular form.

export const CURRENCY_NAMES = {
${LOCALES.map(
  (locale) => `  ${locale}: {
${codes.map((code) => `    ${code}: ${quote(nameOf(code, locale))},`).join('\n')}
  },`,
).join('\n')}
} as const;
`;

writeFileSync(OUT, file, 'utf8');
console.log(`Wrote ${codes.length} currency names in ${LOCALES.length} locales to ${OUT}`);
