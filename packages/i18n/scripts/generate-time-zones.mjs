/**
 * Regenerates `src/timeZones.generated.ts` from the CLDR data bundled with Node's Intl.
 *
 * Run with: pnpm --filter @saldo/i18n generate:time-zones
 *
 * Generated rather than asked of the phone, like the currency names: Hermes cannot be relied on for
 * `timeZoneName: 'longGeneric'`. The zones are `Intl.supportedValuesOf('timeZone')` plus `UTC`.
 * Names repeat a lot (every zone in central Europe is «Ora dell’Europa centrale»), so each locale
 * stores its distinct names once and one index per zone.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'timeZones.generated.ts');

/** App locale → the CLDR locale to read. Keep in step with `SUPPORTED_LOCALES` in `src/format.ts`. */
const LOCALES = [
  ['it', 'it'],
  ['en', 'en'],
  ['fr', 'fr'],
  ['de', 'de'],
  ['sv', 'sv'],
  ['es', 'es'],
  ['pt', 'pt-PT'],
];

const zones = [...new Set([...Intl.supportedValuesOf('timeZone'), 'UTC'])].sort();

/**
 * Current IANA names that CLDR still files under an older id. Phones report the current one
 * (`Asia/Kolkata`), the list holds the old one (`Asia/Calcutta`); without this map the two never
 * compare equal and a user in India is told forever that their phone is elsewhere. Node resolves
 * each to the id it lists; a name it already lists needs no alias.
 */
const CURRENT_NAMES = [
  'Africa/Asmara',
  'America/Argentina/Buenos_Aires',
  'America/Argentina/Catamarca',
  'America/Argentina/Cordoba',
  'America/Argentina/Jujuy',
  'America/Argentina/Mendoza',
  'America/Atikokan',
  'America/Indiana/Indianapolis',
  'America/Kentucky/Louisville',
  'America/Nuuk',
  'Asia/Chongqing',
  'Asia/Ho_Chi_Minh',
  'Asia/Istanbul',
  'Asia/Kathmandu',
  'Asia/Kolkata',
  'Asia/Ulan_Bator',
  'Asia/Yangon',
  'Atlantic/Faroe',
  'Australia/Canberra',
  'Etc/GMT',
  'Etc/UTC',
  'Europe/Kyiv',
  'Europe/Uzhgorod',
  'Europe/Zaporozhye',
  'Pacific/Chuuk',
  'Pacific/Kanton',
  'Pacific/Pohnpei',
];

function listedAs(name) {
  if (name === 'Etc/UTC' || name === 'Etc/GMT') return 'UTC';
  return new Intl.DateTimeFormat('en', { timeZone: name }).resolvedOptions().timeZone;
}

const aliases = CURRENT_NAMES.filter((name) => !zones.includes(name))
  .map((name) => [name, listedAs(name)])
  .filter(([, target]) => zones.includes(target));

/** January, so the generic name is taken outside any daylight-saving switch. */
const AT = new Date(Date.UTC(2026, 0, 15, 12));

function genericName(zone, locale) {
  const name = new Intl.DateTimeFormat(locale, { timeZone: zone, timeZoneName: 'longGeneric' })
    .formatToParts(AT)
    .find((part) => part.type === 'timeZoneName')?.value;
  if (name === undefined || name === '') throw new Error(`No ${locale} name for ${zone}`);
  return name;
}

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const tables = LOCALES.map(([key, locale]) => {
  const names = [];
  const index = new Map();
  const of = zones.map((zone) => {
    const name = genericName(zone, locale);
    if (!index.has(name)) {
      index.set(name, names.length);
      names.push(name);
    }
    return index.get(name);
  });
  return `  ${key}: {
    names: [
${names.map((name) => `      ${quote(name)},`).join('\n')}
    ],
    of: [${of.join(', ')}],
  },`;
});

const file = `// Generated by scripts/generate-time-zones.mjs from Node's CLDR data. Do not edit by hand.
// Source: Intl.supportedValuesOf('timeZone') + 'UTC'; Intl.DateTimeFormat timeZoneName 'longGeneric'.

/** Every IANA zone CLDR knows, by id. */
export const TIME_ZONES: readonly string[] = [
${zones.map((zone) => `  ${quote(zone)},`).join('\n')}
];

/** A current IANA name → the id \`TIME_ZONES\` lists it under. */
export const TIME_ZONE_ALIASES: Readonly<Record<string, string>> = {
${aliases.map(([name, target]) => `  ${quote(name)}: ${quote(target)},`).join('\n')}
};

/** Per locale: the distinct generic names, and for each zone of \`TIME_ZONES\` the index of its name. */
export const TIME_ZONE_GENERIC_NAMES = {
${tables.join('\n')}
} as const;
`;

writeFileSync(OUT, file, 'utf8');
console.log(`Wrote ${zones.length} time zones in ${LOCALES.length} locales to ${OUT}`);
