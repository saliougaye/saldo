/**
 * Regenerates `src/currencies.generated.ts` from the CLDR data bundled with Node's Intl.
 *
 * Run with: pnpm --filter @saldo/core generate:currencies
 *
 * `minorDigits` is CLDR's *practical* currency exponent, not ISO 4217's: CLDR reports 0 for
 * currencies whose minor unit is not used in practice (IQD, ISK), which is what a phone shows
 * everywhere else. Symbols are CLDR narrow symbols resolved in `en` so the table stays
 * locale-independent; `@saldo/i18n` decides prefix/suffix placement per locale.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'currencies.generated.ts');

function minorDigitsOf(code) {
  const { maximumFractionDigits } = new Intl.NumberFormat('en', {
    style: 'currency',
    currency: code,
  }).resolvedOptions();
  return maximumFractionDigits;
}

function symbolOf(code) {
  const parts = new Intl.NumberFormat('en', {
    style: 'currency',
    currency: code,
    currencyDisplay: 'narrowSymbol',
  }).formatToParts(1);
  return parts.find((part) => part.type === 'currency')?.value ?? code;
}

const codes = [...Intl.supportedValuesOf('currency')].sort();
const rows = codes.map((code) => {
  const minorDigits = minorDigitsOf(code);
  if (![0, 2, 3].includes(minorDigits)) {
    throw new Error(`Unexpected minorDigits ${minorDigits} for ${code}`);
  }
  return { code, symbol: symbolOf(code), minorDigits };
});

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const file = `// Generated by scripts/generate-currencies.mjs from Node's CLDR data. Do not edit by hand.
// Source: Intl.supportedValuesOf('currency') + Intl.NumberFormat resolvedOptions/narrowSymbol.

/** Every ISO 4217 code CLDR can format, alphabetically. */
export const CURRENCY_CODES = [
${codes.map((code) => `  ${quote(code)},`).join('\n')}
] as const;

export const CURRENCY_TABLE = {
${rows
  .map(
    ({ code, symbol, minorDigits }) =>
      `  ${code}: { code: ${quote(code)}, symbol: ${quote(symbol)}, minorDigits: ${minorDigits} },`,
  )
  .join('\n')}
} as const;
`;

writeFileSync(OUT, file, 'utf8');
console.log(`Wrote ${rows.length} currencies to ${OUT}`);
